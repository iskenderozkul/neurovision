#pragma once

#include <cstdint>
#include <mutex>
#include <vector>

namespace nv {

struct EventStats {
    float eventRate = 0.f;       // events per second, EMA smoothed
    float density = 0.f;         // fired pixels / total pixels in the last frame
    float posShare = 0.f;        // posCount / (posCount + negCount), 0.5 when empty
    int posCount = 0;            // last frame positive event count
    int negCount = 0;            // last frame negative event count
    float threshold = 0.20f;     // active log-intensity threshold C
    float meanMagnitude = 0.f;   // mean |delta log| over fired pixels (last frame)
    float processMs = 0.f;       // wall time of the last process() call
    int64_t timestampNs = 0;     // timestamp of the last processed frame
};

// Software DVS simulation: a normal camera frame is downsampled, converted to
// log intensity, and compared against a per-pixel reference. A pixel emits an
// event only when its log intensity crosses the threshold relative to that
// reference, then the reference snaps to the current value. This is an
// event-camera-style encoding of the same measurements, not new information:
// at most one event per output pixel per input frame, so the temporal
// resolution is still bounded by the camera FPS.
class EventEngine {
public:
    static constexpr int kWidth = 320;
    static constexpr int kHeight = 240;

    EventEngine();

    // gray: 8-bit luma, width x height, rowStride in bytes (>= width).
    // Returns the number of events generated by this frame. Thread-safe.
    int process(const uint8_t* gray, int width, int height, int rowStride,
                int64_t timestampNs);

    void setThreshold(float c);   // clamp to [0.02, 1.0]
    float threshold() const;
    void setDecay(float d);       // clamp to [0.0, 0.995]; preview persistence
    void reset();

    // ARGB_8888 preview, kWidth * kHeight, row-major (top-down).
    void preview(uint32_t* argbOut) const;
    // Normalised event density 0..255, kWidth * kHeight.
    void densityGrid(uint8_t* out) const;
    // Current-frame events per pixel: +1 positive, -1 negative, 0 no event.
    // kWidth * kHeight. (Contour/edge selection for the event cloud.)
    void copyEvents(int8_t* out, int maxEvents) const;

    EventStats stats() const;

private:
    // Box-average the source footprint of each output pixel into luma_.
    void downsample(const uint8_t* gray, int width, int height, int rowStride);

    mutable std::mutex mutex_;
    std::vector<uint8_t> luma_;    // current downsampled luma, kWidth * kHeight
    std::vector<float> ref_;       // per-pixel reference log intensity
    std::vector<float> posAcc_;    // decaying positive-event accumulation
    std::vector<float> negAcc_;    // decaying negative-event accumulation
    std::vector<int8_t> lastEvents_; // current-frame +1/-1/0 per pixel
    float logLut_[256] = {};       // logf(1 + v), immutable after construction
    float decay_ = 0.86f;          // preview accumulator persistence
    bool initialized_ = false;     // first frame after reset only seeds ref_
    bool hasRate_ = false;         // event-rate EMA has a previous sample
    EventStats stats_;             // last-frame counters / settings snapshot
};

}  // namespace nv
